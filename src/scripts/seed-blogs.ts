async function seed() {
  console.log("🌱 Starting Blog seeding...\n");

  const uploadCache = new Map<string, string>();
  const upload = async (file: string) => {
    if (uploadCache.has(file)) return uploadCache.get(file)!;
    const url = await uploadFile(file);
    uploadCache.set(file, url);
    return url;
  };

  for (const item of BLOGS_SEED) {
    const image = await upload(item.file);
    const data = {
      title: item.title,
      author: item.author,
      category: item.category,
      image,
      date: item.date,
      excerpt: item.excerpt,
      content: item.content,
      createdAt: serverTimestamp(),
    };

    console.log(`Writing blog post: ${item.id}...`);
    await setDoc(doc(db, "blogs", item.id), data);
  }

  console.log("\n✅ Blog seeding completed!");
  process.exit(0);
}

seed().catch((e) => {
  console.error("Blog seeding failed:", e);
  process.exit(1);
});
